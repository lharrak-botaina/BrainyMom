// Save/load per-lesson progress (localStorage — always used as fast local cache)
function triggerSync(){ try{ window.dispatchEvent(new Event("bm_sync")); }catch{} }
function saveProgress(id, data){ try{ localStorage.setItem("lp_"+id, JSON.stringify(data)); triggerSync(); }catch{} }
function loadProgress(id){ try{ return JSON.parse(localStorage.getItem("lp_"+id)||"null"); }catch{ return null; } }
function clearProgress(id){ try{ localStorage.removeItem("lp_"+id); clearExState(id); }catch{} }

function saveExState(id, phase, data){ try{ localStorage.setItem("lex_"+id+"_"+phase, JSON.stringify(data)); }catch{} }
function loadExState(id, phase){ try{ return JSON.parse(localStorage.getItem("lex_"+id+"_"+phase)||"null"); }catch{ return null; } }
function clearExState(id){ try{ for(let i=0;i<5;i++) localStorage.removeItem("lex_"+id+"_"+i); }catch{} }

// ─── Firestore sync helpers ───
function gatherUserData(){
  const data={
    xp:+(localStorage.getItem("lx")||0),
    streak:+(localStorage.getItem("ls")||0),
    weekXp:{},completed:[],
    lessonProgress:{},exerciseState:{},
    screen:localStorage.getItem("l_screen")||"home",
    openId:localStorage.getItem("l_openId")||null,
    openType:localStorage.getItem("l_openType")||null,
  };
  try{data.weekXp=JSON.parse(localStorage.getItem("lw")||"{}");}catch{}
  try{data.completed=JSON.parse(localStorage.getItem("lc")||"[]");}catch{}
  // gather lesson progress & exercise state
  const allIds=[...FRENCH_LESSONS,...MATH_LESSONS,...SCIENCE_LESSONS].map(l=>l.id);
  for(const id of allIds){
    const lp=loadProgress(id); if(lp) data.lessonProgress[id]=lp;
    for(let p=0;p<5;p++){
      const ex=loadExState(id,p); if(ex) data.exerciseState[id+"_"+p]=ex;
      const exqs=loadExState(id,p+"_qs"); if(exqs) data.exerciseState[id+"_"+p+"_qs"]=exqs;
    }
    const exqe=loadExState(id,"qe"); if(exqe) data.exerciseState[id+"_qe"]=exqe;
  }
  return data;
}

function hydrateFromCloud(data){
  if(!data)return;
  if(data.xp!=null) localStorage.setItem("lx",data.xp);
  if(data.streak!=null) localStorage.setItem("ls",data.streak);
  if(data.weekXp) localStorage.setItem("lw",JSON.stringify(data.weekXp));
  if(data.completed) localStorage.setItem("lc",JSON.stringify(data.completed));
  if(data.screen) localStorage.setItem("l_screen",data.screen);
  if(data.openId) localStorage.setItem("l_openId",data.openId); else localStorage.removeItem("l_openId");
  if(data.openType) localStorage.setItem("l_openType",data.openType); else localStorage.removeItem("l_openType");
  if(data.lessonProgress){
    for(const[id,v]of Object.entries(data.lessonProgress)){
      localStorage.setItem("lp_"+id,JSON.stringify(v));
    }
  }
  if(data.exerciseState){
    for(const[key,v]of Object.entries(data.exerciseState)){
      localStorage.setItem("lex_"+key,JSON.stringify(v));
    }
  }
}

export default function App(){
  // ─── Auth state ───
  const[user,setUser]=useState(null);
  const[authLoading,setAuthLoading]=useState(true);
  const[guestMode,setGuestMode]=useState(()=>localStorage.getItem("l_guest")==="1");
  const[dataVersion,setDataVersion]=useState(0); // bump to force MainApp remount after cloud hydration
  const syncTimer=useRef(null);
  const isSyncing=useRef(false);

  // Debounced sync to Firestore
  const scheduleSync=useCallback(()=>{
    if(!auth.currentUser)return;
    clearTimeout(syncTimer.current);
    syncTimer.current=setTimeout(async()=>{
      try{
        const data=gatherUserData();
        await setDoc(doc(db,"users",auth.currentUser.uid),{...data,updatedAt:serverTimestamp()},{merge:true});
      }catch(e){console.warn("Sync error:",e);}
    },2000);
  },[]);

  useEffect(()=>{
    const unsub=onAuthStateChanged(auth,(u)=>{
      setUser(u);
      setAuthLoading(false);
      if(u) loadCloudData(u.uid);
    });
    const onSync=()=>scheduleSync();
    window.addEventListener("bm_sync",onSync);
    return ()=>{ unsub(); window.removeEventListener("bm_sync",onSync); };
  },[]);

  // Load cloud data on login, merge with local
  const loadCloudData=async(uid)=>{
    if(isSyncing.current)return;
    isSyncing.current=true;
    try{
      const snap=await getDoc(doc(db,"users",uid));
      if(snap.exists()){
        const cloud=snap.data();
        const local=gatherUserData();
        if((cloud.xp||0)>(local.xp||0)){
          // Cloud is ahead — hydrate localStorage and remount
          hydrateFromCloud(cloud);
          setDataVersion(v=>v+1);
        }else{
          // Local is ahead or equal — push to cloud
          await setDoc(doc(db,"users",uid),{...local,updatedAt:serverTimestamp()},{merge:true});
        }
      }else{
        // First time login — push local data to cloud
        const local=gatherUserData();
        await setDoc(doc(db,"users",uid),{...local,updatedAt:serverTimestamp()});
      }
    }catch(e){console.warn("Cloud sync failed:",e);}
    finally{isSyncing.current=false;}
  };

  const doLogin=async()=>{
    try{
      const isMobile=/iPhone|iPad|iPod|Android/i.test(navigator.userAgent);
      if(isMobile) await signInWithRedirect(auth,googleProvider);
      else await signInWithPopup(auth,googleProvider);
      localStorage.removeItem("l_guest");
      setGuestMode(false);
    }catch(e){console.error("Login error:",e);}
  };
  const doLogout=async()=>{
    await signOut(auth);
    setUser(null);
  };
  const enterGuest=()=>{localStorage.setItem("l_guest","1");setGuestMode(true);};

  // ─── Show login screen if not authenticated and not guest ───
  if(authLoading) return <LoadingScreen/>;
  if(!user&&!guestMode) return <LoginScreen onLogin={doLogin} onGuest={enterGuest}/>;

  // ─── Main app — key={dataVersion} forces remount when cloud data is hydrated ───
  return <MainApp key={dataVersion} user={user} onLogout={doLogout} scheduleSync={scheduleSync} onLogin={doLogin}/>;
}

