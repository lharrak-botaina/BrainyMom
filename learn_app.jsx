/* ─── FRENCH FLOW: explain→flash→mcq→write ─── */
function FrenchFlow({lesson,onBack,onComplete}){
  const saved=loadProgress(lesson.id);
  const[phase,setPhase]=useState(()=>saved?.phase||0);
  const[sc,setSc]=useState(()=>saved?.sc||{mcq:0,wr:0});
  const next=(d={})=>{
    const newSc={...sc};
    if(d.mcq!=null)newSc.mcq=d.mcq;
    if(d.wr!=null)newSc.wr=d.wr;
    setSc(newSc);
    const newPhase=phase+1;
    setPhase(newPhase);
    saveProgress(lesson.id,{phase:newPhase,sc:newSc});
  };
  if(phase===4){
    const pts=sc.mcq*8+sc.wr*12;
    return<Done emoji="🎉" title="رائعة!" sub={`${sc.mcq+sc.wr} إجابة صحيحة`} pts={pts} onContinue={()=>onComplete(pts)}/>;
  }
  return(
    <div style={S.root}>
      <style>{CSS}</style>
      <LH title={`${lesson.emoji} ${lesson.title}`} onBack={onBack} phase={phase} phases={["الشرح","البطاقات","اختيار","كتابة"]} color={lesson.color}/>
      {phase===0&&<ExplainFr lesson={lesson} onNext={()=>next()}/>}
      {phase===1&&<FlashCards words={lesson.words} color={lesson.color} onNext={()=>next()}/>}
      {phase===2&&<MCQFr words={lesson.words} color={lesson.color} lessonId={lesson.id} onNext={(s)=>next({mcq:s})}/>}
      {phase===3&&<WriteFr words={lesson.words} color={lesson.color} lessonId={lesson.id} onNext={(s)=>next({wr:s})}/>}
    </div>
  );
}

